import 'package:flutter/material.dart';
import '../../../core/app_info/app_version_info.dart';

Future<void> showStudyBibleAboutDialog(BuildContext context) async {
  final version = await AppVersionInfo.versionWithBuild();
  if (!context.mounted) return;
  await showDialog<void>(
    context: context,
    builder: (context) => AlertDialog(
      title: const Text('About'),
      scrollable: true,
      content: Text(
        'Biblical Heritage #StudyBible\n'
        'Version $version\n'
        '© 2026 Biblical Heritage\n'
        'Built with Flutter.\n\n'
        'Audio narration\n'
        'The narration supplied with this app for the Bible, library, and extended library is generated by artificial intelligence and designed to sound natural and lifelike. The narration heard by listeners is synthesized speech, not a recorded human reading.\n\n'
        'Pronunciation guidance\n'
        "Care is taken to review biblical-name pronunciations with reference to the Dictionary of Scripture Proper Names, with Their Pronunciation and Meanings, in Oxford University Press's Helps to the Study of the Bible, as reproduced by the Christian Classics Ethereal Library. Additional references consulted include Hermann Michaelis and Daniel Jones, A Phonetic Dictionary of the English Language (1913), and the Zondervan Pictorial Encyclopedia of the Bible, accessed through Bible Gateway. Established pronunciation variants may occur, and synthesized narration may occasionally contain errors.\n\n"
        'Cross-reference data derived from the OpenBible.info Bible Cross References dataset, licensed under Creative Commons Attribution 4.0.\n'
        'https://www.openbible.info/labs/cross-references/\n\n'
        'Help: open Utilities for setup tools, then Bible Explorer for study controls and tutorials.',
      ),
      actions: [
        TextButton(
          onPressed: () => Navigator.of(context).pop(),
          child: const Text('Close'),
        ),
      ],
    ),
  );
}
