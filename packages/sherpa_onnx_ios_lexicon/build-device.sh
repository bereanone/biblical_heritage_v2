#!/bin/bash
# Usage: bash build-device.sh PATCHED_SHERPA_SOURCE ONNX_IOS_ARM64_DIR OUTPUT_DIR
# Apply dictionary-mode.patch to pinned source first. Dependencies follow source CMake pins.
set -euo pipefail
source_dir=$(cd "$1" && pwd)
export SHERPA_ONNXRUNTIME_LIB_DIR=$(cd "$2" && pwd)
export SHERPA_ONNXRUNTIME_INCLUDE_DIR="$SHERPA_ONNXRUNTIME_LIB_DIR/onnxruntime.framework/Headers"
cmake -S "$source_dir" -B "$3" \
  -DCMAKE_TOOLCHAIN_FILE="$source_dir/toolchains/ios.toolchain.cmake" \
  -DPLATFORM=OS64 -DENABLE_BITCODE=0 -DENABLE_ARC=1 -DENABLE_VISIBILITY=0 \
  -DCMAKE_BUILD_TYPE=Release -DBUILD_SHARED_LIBS=OFF -DDEPLOYMENT_TARGET=13.0 \
  -DCMAKE_POLICY_VERSION_MINIMUM=3.5 -DSHERPA_ONNX_ENABLE_C_API=ON \
  -DSHERPA_ONNX_ENABLE_PYTHON=OFF -DSHERPA_ONNX_ENABLE_BINARY=OFF \
  -DSHERPA_ONNX_ENABLE_TESTS=OFF -DSHERPA_ONNX_ENABLE_CHECK=OFF \
  -DSHERPA_ONNX_ENABLE_PORTAUDIO=OFF -DSHERPA_ONNX_ENABLE_JNI=OFF \
  -DSHERPA_ONNX_ENABLE_WEBSOCKET=OFF -DSHERPA_ONNX_ENABLE_SPEAKER_DIARIZATION=OFF \
  -DSHERPA_ONNX_BUILD_C_API_EXAMPLES=OFF -DBUILD_PIPER_PHONMIZE_EXE=OFF \
  -DBUILD_PIPER_PHONMIZE_TESTS=OFF -DBUILD_ESPEAK_NG_EXE=OFF -DBUILD_ESPEAK_NG_TESTS=OFF
cmake --build "$3" --target sherpa-onnx-c-api --parallel 2
