String expandedLibraryBibleBook(String source) {
  final value = source
      .replaceAll('.', '')
      .trim()
      .replaceFirstMapped(
        RegExp(r'^(III|II|I)\s+', caseSensitive: false),
        (m) => '${{'I': 1, 'II': 2, 'III': 3}[m[1]!.toUpperCase()]} ',
      )
      .replaceAll(RegExp(r'\s+'), ' ');
  return libraryBibleBookAliases[value.toLowerCase()] ?? value;
}

String libraryBibleBookPattern() {
  final aliases = <String>{};
  for (final entry in libraryBibleBookAliases.entries) {
    if (entry.value == 'Chapter') continue;
    final alias = entry.key.replaceAll('.', '');
    aliases.add(alias);
    final numbered = RegExp(r'^([123]) (.+)$').firstMatch(alias);
    if (numbered != null) {
      aliases.add(
        '${['I', 'II', 'III'][int.parse(numbered[1]!) - 1]} ${numbered[2]}',
      );
    }
  }
  final ordered = aliases.toList()
    ..sort((a, b) => b.length.compareTo(a.length));
  return '(?:${ordered.map((a) => RegExp.escape(a).replaceAll(' ', r'\s+')).join('|')})';
}
